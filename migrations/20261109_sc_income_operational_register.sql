-- Operational income only; no payment, GL journal, or canonical bank mutation.
CREATE TABLE IF NOT EXISTS sport_center.sc_income_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry_key uuid NOT NULL UNIQUE,
 transaction_date date NOT NULL,
 source_name text NOT NULL CHECK (length(btrim(source_name)) BETWEEN 2 AND 160),
 sender_bank text NOT NULL CHECK (length(btrim(sender_bank)) BETWEEN 2 AND 120),
 method text NOT NULL CHECK (method IN ('Transfer Bank','Tunai','QRIS','Lainnya')),
 receiving_account text NOT NULL CHECK (length(btrim(receiving_account)) <= 160),
 amount numeric(18,0) NOT NULL CHECK (amount > 0 AND amount < 1000000000000),
 bank_reference text,
 fingerprint text NOT NULL UNIQUE,
 reconciliation_state text NOT NULL DEFAULT 'UNVERIFIED' CHECK (reconciliation_state IN ('UNVERIFIED','REVIEW_REQUIRED')),
 sheet_sync_state text NOT NULL DEFAULT 'pending' CHECK (sheet_sync_state IN ('pending','syncing','synced','failed','disabled')),
 sheet_sync_error text,
 sheet_sync_attempts integer NOT NULL DEFAULT 0,
 sheet_sync_started_at timestamptz,
 sheet_synced_at timestamptz,
 sheet_row integer,
 created_by integer,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT sc_income_reference_length CHECK(bank_reference IS NULL OR length(bank_reference)<=120)
);
CREATE INDEX IF NOT EXISTS sc_income_entries_date_idx ON sport_center.sc_income_entries(transaction_date DESC,id DESC);
CREATE INDEX IF NOT EXISTS sc_income_entries_sync_idx ON sport_center.sc_income_entries(sheet_sync_state,updated_at);
CREATE UNIQUE INDEX IF NOT EXISTS sc_income_entries_reference_unique ON sport_center.sc_income_entries
 (transaction_date, lower(receiving_account),lower(bank_reference))
 WHERE bank_reference IS NOT NULL AND btrim(bank_reference)<>'';
ALTER TABLE sport_center.sc_income_entries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON sport_center.sc_income_entries FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE sport_center.sc_income_entries_id_seq FROM PUBLIC, anon, authenticated;
