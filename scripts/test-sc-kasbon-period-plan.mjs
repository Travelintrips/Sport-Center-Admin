import assert from "node:assert/strict";
import {planNewPeriod,buildPeriodCells,nextPeriod} from "../artifacts/api-server/src/lib/scKasbonPeriodPlan.ts";
const formatted=Array.from({length:1080},()=>[]);
const unformatted=Array.from({length:1080},()=>[]);
const put=(rows,r,c,value)=>{rows[r-1][c-1]=value;};
put(formatted,1041,1,"November");
put(formatted,1042,1,"Tanggal");put(formatted,1042,2,"Keterangan");
put(unformatted,1042,5,46327); // will be overridden with exact date serial below
put(unformatted,1042,5,(Date.UTC(2026,10,1)-Date.UTC(1899,11,30))/86400000);
put(formatted,1043,2,"Kasbon Robby");
put(formatted,1044,2,"sonic");
put(formatted,1045,2,"Total");
const plan=planNewPeriod(formatted,unformatted,"2026-12","previous_total");
assert.equal(plan.sourceStart,1041);
assert.equal(plan.sourceEnd,1045);
assert.equal(plan.destinationStart,1048);
assert.equal(plan.destinationEnd,1052);
assert.equal(plan.employeeCount,2);
assert.equal(nextPeriod("2026-12"),"2027-01");
const cells=buildPeriodCells(plan);
assert.equal(cells[0][0].userEnteredValue.stringValue,"Desember");
assert.equal(cells[1][4].userEnteredValue.numberValue,(Date.UTC(2026,11,1)-Date.UTC(1899,11,30))/86400000);
assert.equal(cells[2][3].userEnteredValue.formulaValue,"=C1043");
assert.equal(cells[2][2].userEnteredValue.formulaValue,"=SUM(D1050:AI1050)");
assert.equal(cells[4][2].userEnteredValue.formulaValue,"=SUM(C1050:C1051)");
assert.equal(cells[4][34].userEnteredValue.formulaValue,"=SUM(AI1050:AI1051)");
const zero=buildPeriodCells(planNewPeriod(formatted,unformatted,"2026-12","zero"));
assert.equal(zero[2][3].userEnteredValue.numberValue,0);
assert.throws(()=>planNewPeriod(formatted,unformatted,"2027-01","zero"),/PREVIOUS_PERIOD/);
assert.throws(()=>planNewPeriod(formatted,unformatted,"2026-10","zero"),/PREVIOUS_PERIOD/);
const duplicate=formatted.map(r=>r.slice());
put(duplicate,1042,5,"11-1-2026");
assert.throws(()=>planNewPeriod(duplicate,unformatted,"2026-11","zero"),/PERIOD_ALREADY_EXISTS/);
const after=formatted.map(r=>r.slice());
put(after,1055,2,"Do not overwrite");
assert.throws(()=>planNewPeriod(after,unformatted,"2026-12","zero"),/HISTORICAL_DATA_AFTER_SOURCE_BLOCK/);
assert.throws(()=>planNewPeriod(formatted,unformatted,"2026-12","unverified"),/CARRY_MODE_REQUIRED/);
console.log("PASS: period generator December/January, formulas, carryover, duplicate/missing/historical protection");
