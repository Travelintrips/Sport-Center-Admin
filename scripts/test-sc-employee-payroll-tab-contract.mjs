import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const ui=readFileSync("artifacts/sport-center/src/pages/admin/SCEmployees.tsx","utf8");
const dialog=readFileSync("artifacts/sport-center/src/pages/admin/PayrollTabDialog.tsx","utf8");
const routes=readFileSync("artifacts/api-server/src/routes/scEmployeePayrollTabs.ts","utf8");
const registered=readFileSync("artifacts/api-server/src/routes/index.ts","utf8");
assert.match(ui,/Tab Gaji Bulanan/);
assert.match(ui,/<PayrollTabDialog\/>/);
assert.match(dialog,/Buat Tab Gaji Baru/);
assert.match(dialog,/Pratinjau Tab/);
assert.match(dialog,/Buat Tab Gaji/);
assert.match(dialog,/preview\?\.writeEnabled/);
assert.match(routes,/PAYROLL_TAB_ALREADY_EXISTS/);
assert.match(routes,/count>20000\|\|cols<13\|\|cols>2000/,"allocated grid must not be limited to 200 rows");
assert.match(routes,/PAYROLL_TEMPLATE_POPULATED_ROWS_UNSAFE/,"populated A:M must still have 200-row safety bound");
assert.ok(routes.includes(`sourceTitle.replace(/'/g,"''")+"'!A:M"`),"read real populated rows not grid allocation");
assert.doesNotMatch(routes,/count>200\|\|cols<13/);

assert.match(routes,/SC_SALARY_TAB_CREATE_ENABLED/);
assert.match(routes,/APP_ENV!=="production"\|\|process\.env\.NODE_ENV!=="production"/);
assert.match(routes,/newSheetName:plan\.targetTitle/);
assert.match(routes,/hidden:true/);
assert.match(routes,/hidden:false/);
assert.doesNotMatch(routes,/values\\.batchClear/,"no prior-month payroll data should be cleared");
assert.match(routes,/PAYROLL_FULL_COPY_READBACK_FAILED/);
assert.match(routes,/PAYROLL_REPAIR_CONFLICT_NONEMPTY_CELLS/);
assert.match(routes,/PAYROLL_REPAIR_READBACK_MISMATCH/);
assert.match(routes,/restore-december-preview/);
assert.match(routes,/restore-december"/);
assert.match(dialog,/Pratinjau Pemulihan Desember/);
assert.match(dialog,/Pulihkan Data Desember/);
assert.match(routes,/PAYROLL_FULL_COPY_READBACK_FAILED/);
assert.match(routes,/SC_PAYROLL_MONTHLY_TAB_CREATED/);
assert.match(registered,/router\.use\(scEmployeePayrollTabsRouter\)/);
assert.doesNotMatch(routes,/SC_KASBON_POOL_SPREADSHEET_ID/);
console.log("PASS: salary tab preview/create is explicit, guarded, and independent of Kasbon POOL");
