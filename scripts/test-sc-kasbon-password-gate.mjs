import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const route=readFileSync("artifacts/api-server/src/routes/scEmployeeKasbon.ts","utf8");
const gate=readFileSync("artifacts/api-server/src/lib/scKasbonActionGate.ts","utf8");
const ui=readFileSync("artifacts/sport-center/src/pages/admin/SCEmployeeKasbon.tsx","utf8");
assert.match(route,/kasbon\/:id\/unlock/);
assert.match(route,/verifyKasbonPassword\(req\.body\.password,actor\.userId/);
const patch=route.slice(route.indexOf('router.patch("/admin/sc-employees/:employeeId/kasbon/:id"'),route.indexOf('// Delete exactly one record'));
const del=route.slice(route.indexOf('router.delete("/admin/sc-employees/:employeeId/kasbon/:id"'),route.indexOf('Manual one-record trigger'));
assert.match(patch,/requireKasbonActionGrant\(req,res\)/,"PATCH must be server protected");
assert.match(del,/requireKasbonActionGrant\(req,res\)/,"DELETE must be server protected");
assert.match(gate,/bcrypt\.compare\(password,conf\.hash\)/,"hash, not plain password compare");
assert.match(gate,/timingSafeEqual\(expected,actual\)/);
assert.match(gate,/payload\.uid===userId && payload\.employeeId===employeeId && payload\.recordId===recordId/);
assert.match(gate,/SC_KASBON_ACTION_PASSWORD_HASH/);
assert.match(gate,/SC_KASBON_ACTION_SIGNING_KEY/);
assert.match(gate,/MAX_ATTEMPTS = 5/);
assert.match(ui,/Insert Password/);
assert.match(ui,/hasActionGrant\(r\.id\)\?</);
assert.match(ui,/x-sc-kasbon-authorization/);
assert.match(ui,/setActionPassword\(""/);
assert.match(ui,/actionPassword.length===0/,"filled password should enable submit regardless of length");
assert.doesNotMatch(ui,/actionPassword.length<12/,"UI should not block already configured shorter password");
const unlockDialog=ui.slice(ui.indexOf('<Dialog open={unlockRecord!==null}'),ui.indexOf('<Dialog open={toDelete!==null}'));
assert.doesNotMatch(unlockDialog,/<form\\b/,"authorization input must not impersonate a Chrome login form");
assert.match(unlockDialog,/name="kasbon-action-authorization-only"/);
assert.match(unlockDialog,/type="password"/,"input must still mask password");
assert.match(unlockDialog,/autoComplete="off"/);
assert.match(unlockDialog,/data-lpignore="true"/);
assert.match(unlockDialog,/type="button" disabled=\\{unlockAction\\.isPending\\|\\|actionPassword\\.length===0\\} onClick=\\{\\(\\)=>unlockAction\\.mutate\\(\\)\\}/);
assert.match(unlockDialog,/onKeyDown=\\{e=>\\{if\\(e\\.key==="Enter"\\)/);
assert.doesNotMatch(unlockDialog,/type="submit"/,"password manager should not see submit event");

assert.doesNotMatch(route,/admin\|owner\|super_admin.*unlock/i);
console.log("PASS: password gate required on PATCH and DELETE, role cannot bypass, UI locked and short-lived scoped authorization");
