import assert from "node:assert/strict";
import {summarizeKasbonPool} from "./auditKasbonPool.mjs";
const rows=Array.from({length:1060},()=>[]);
const put=(r,c,v)=>{rows[r-1][c-1]=v;};
put(1041,1,"November");
put(1042,1,"Tanggal");put(1042,2,"Keterangan");put(1042,3,"TOTAL");put(1042,4,"sisa kasbon Oktober");
put(1042,5,"11-1-2026");put(1042,6,"11-2-2026");put(1042,9,"11-5-2026");
put(1043,1,"1");put(1043,2,"Kasbon Karyawan Uji A");put(1043,3,"=SUM(D1043:AI1043)");
put(1044,1,"2");put(1044,2,"Kasbon Karyawan Uji B");put(1044,3,"=SUM(D1044:AI1044)");
put(1044,9,1500000);
put(1045,2,"Total");put(1045,3,"=SUM(C1043:C1044)");
const r=summarizeKasbonPool(rows,rows,{title:"test"});
assert.equal(r.november2026.length,1);
assert.equal(r.november2026[0].headerRow,1042);
assert.equal(r.november2026[0].totalRow,1045);
assert.equal(r.november2026[0].employeeRows.length,2);
assert.equal(r.november2026[0].occupiedDailyCells,1);
assert.ok(r.november2026[0].formulaCells.length>=3);
assert.ok(r.warnings.includes("FORMULA_PROTECTED_CELLS_PRESENT"));
assert.ok(r.warnings.includes("EXISTING_DAILY_ENTRIES_PRESENT"));
assert.equal(r.writePermission,"DISABLED_READ_ONLY_AUDIT");
const empty=summarizeKasbonPool([],[]);
assert.ok(empty.warnings.includes("NOVEMBER_2026_NOT_FOUND"));
console.log("PASS: Kasbon POOL audit detects month, protected formula cells, occupied daily cells, subtotal rows and no-write mode");
