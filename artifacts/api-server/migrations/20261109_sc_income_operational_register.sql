-- Operational SC income only. No GL, payments or verified bank_mutations.
CREATE TABLE IF NOT EXISTS sport_center.sc_income_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry_key uuid NOT NULL UNIQUE,
 fingerprint text NOT NULL UNIQUE,
 transaction_date date NOT NULL,
 source_name text NOT NULL CHECK (char_length(btrim(source_name)) BETWEEN 2 AND 150),
 sender_bank text NOT NULL CHECK (char_length(btrim(sender_bank)) BETWEEN 2 AND 100),
 method text NOT NULL CHECK (method IN ('Transfer Bank','Tunai','QRIS','Lainnya')),
 receiving_account text NOT NULL CHECK (char_length(btrim(receiving_account)) BETWEEN 2 AND 150),
 amount numeric(16,0) NOT NULL CHECK (amount > 0 AND amount <= 1000000000000),
 bank_reference text,
 reconciliation_state text NOT NULL DEFAULT 'UNVERIFIED' CHECK (reconciliation_state='UNVERIFIED'),
 sheet_sync_state text NOT NULL DEFAULT 'pending' CHECK (sheet_sync_state IN ('pending','syncing','synced','failed','disabled')),
 sheet_sync_error text,
 sheet_sync_started_at timestamptz,
 sheet_synced_at timestamptz,
 sheet_row integer,
 created_by integer,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sc_income_date_idx ON sport_center.sc_income_entries(transaction_date DESC,id DESC);
CREATE INDEX IF NOT EXISTS sc_income_sync_idx ON sport_center.sc_income_entries(sheet_sync_state,created_at);
ALTER TABLE sport_center.sc_income_entries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE sport_center.sc_income_entries FROM anon,authenticated;
REVOKE ALL ON SEQUENCE sport_center.sc_income_entries_id_seq FROM anon,authenticated;
