CREATE TABLE IF NOT EXISTS sport_center.gym_x904_access_snapshots (
  snapshot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_serial text NOT NULL,
  observed_at timestamptz NOT NULL,
  user_count integer NOT NULL CHECK (user_count BETWEEN 0 AND 10000),
  users jsonb NOT NULL CHECK (
    jsonb_typeof(users) = 'array' AND jsonb_array_length(users) = user_count
  )
